"""Connection settings: explicit arguments, then environment, then client.env."""

from __future__ import annotations

import os
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Mapping, Optional, Union
from urllib.parse import urlsplit

from .errors import ConfigError

ENV_KEYS = ("MXA_SOCKET_PATH", "MXA_URL", "MXA_MACHINE", "MXA_SECRET")
SOCKET_NAME = "mxagent.sock"
_SECRET_RE = re.compile(r"[A-Za-z0-9_-]{32,256}")
_MACHINE_RE = re.compile(r"[a-z0-9-]{1,32}")


@dataclass(frozen=True)
class Settings:
    socket_path: Optional[str] = None
    url: Optional[str] = None
    machine: Optional[str] = None
    secret: Optional[str] = None

    @property
    def remote(self) -> bool:
        return self.url is not None

    def __repr__(self) -> str:
        secret = "***" if self.secret else None
        return (
            f"Settings(socket_path={self.socket_path!r}, url={self.url!r}, "
            f"machine={self.machine!r}, secret={secret!r})"
        )


def validate_remote(url: Optional[str], machine: Optional[str], secret: Optional[str]) -> None:
    """Raises ConfigError unless url, machine name and secret are usable for the secure WebSocket transport.

    The secret is checked verbatim (no trimming): 32-256 characters of base64url without padding.
    """
    if not url:
        raise ConfigError("remote mode needs MXA_URL")
    if not url.startswith(("ws://", "wss://")):
        raise ConfigError("MXA_URL must start with ws:// or wss://")
    try:
        parsed = urlsplit(url)
        host = parsed.hostname
        parsed.port  # raises ValueError for an invalid port
    except ValueError:
        raise ConfigError("MXA_URL is not a valid URL") from None
    if not host:
        raise ConfigError("MXA_URL has no host")
    if not machine or not secret:
        raise ConfigError("remote mode needs a machine name and secret (MXA_MACHINE, MXA_SECRET)")
    if not _MACHINE_RE.fullmatch(machine):
        raise ConfigError("MXA_MACHINE must match [a-z0-9-]{1,32}")
    if not _SECRET_RE.fullmatch(secret):
        raise ConfigError("MXA_SECRET must be 32-256 characters of [A-Za-z0-9_-] (as generated by mxagentctl)")


def client_env_path(env: Mapping[str, str]) -> Path:
    base = env.get("XDG_CONFIG_HOME") or os.path.join(os.path.expanduser("~"), ".config")
    return Path(base) / "mxagent" / "client.env"


def parse_env_file(text: str) -> dict[str, str]:
    out: dict[str, str] = {}
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        if line.startswith("export "):
            line = line[len("export "):]
        key, value = line.split("=", 1)
        key, value = key.strip(), value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        if key in ENV_KEYS:
            out[key] = value
    return out


def _read_env_file(path: Path) -> dict[str, str]:
    try:
        return parse_env_file(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError):
        return {}


def default_socket_path(env: Mapping[str, str]) -> str:
    """Same default as the daemon."""
    if env.get("XDG_RUNTIME_DIR"):
        return os.path.join(env["XDG_RUNTIME_DIR"], SOCKET_NAME)
    state = env.get("MXA_STATE_DIR") or os.path.join(
        env.get("XDG_STATE_HOME") or os.path.join(os.path.expanduser("~"), ".local", "state"),
        "mxagent",
    )
    return os.path.join(state, "bridge.sock")


def resolve(
    socket_path: Optional[str] = None,
    url: Optional[str] = None,
    machine: Optional[str] = None,
    secret: Optional[str] = None,
    env: Optional[Mapping[str, str]] = None,
    env_file: Optional[Union[str, Path]] = None,
) -> Settings:
    """Remote mode is used when a URL is configured, unless a socket path was passed explicitly.

    Empty values count as unset. Raises ConfigError for an invalid ws(s) URL, a missing or invalid
    machine name, or a missing or malformed secret.
    """
    env = os.environ if env is None else env
    file_values = _read_env_file(Path(env_file) if env_file else client_env_path(env))

    def pick(arg: Optional[str], key: str) -> Optional[str]:
        if arg:
            return arg
        return env.get(key) or file_values.get(key) or None

    if socket_path:
        return Settings(socket_path=socket_path)

    url_value = pick(url, "MXA_URL")
    if url_value:
        machine_value = pick(machine, "MXA_MACHINE")
        secret_value = pick(secret, "MXA_SECRET")
        validate_remote(url_value, machine_value, secret_value)
        return Settings(url=url_value, machine=machine_value, secret=secret_value)

    return Settings(socket_path=pick(None, "MXA_SOCKET_PATH") or default_socket_path(env))
